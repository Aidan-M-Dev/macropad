"""Extract enclosure datums and the existing keycap/OLED drawing outlines."""
import re,json,math
from paths import GENERATED, PCB
GENERATED.mkdir(parents=True, exist_ok=True)
source=PCB
tokens=re.findall(r'\(|\)|"(?:\\.|[^"\\])*"|[^\s()]+',source.read_text())
def parse(i):
 a=[];i+=1
 while tokens[i]!=')':
  if tokens[i]=='(': v,i=parse(i);a.append(v)
  else:
   t=tokens[i];a.append(json.loads(t) if t.startswith('"') else t);i+=1
 return a,i+1
b,_=parse(0)
def kids(a,k): return [x for x in a if isinstance(x,list) and x and x[0]==k]
def get(a,k,d=None):
 v=kids(a,k);return v[0][1:] if v else (d or [])
def prop(a,k):return next((x[2] for x in kids(a,'property') if x[1]==k),'')
edges=[v for v in b if isinstance(v,list) and v[0] in ['gr_line','gr_arc'] and get(v,'layer')==['Edge.Cuts']]
points=[list(map(float,get(e,k)[:2])) for e in edges for k in ['start','end']]
xmin=min(p[0] for p in points);xmax=max(p[0] for p in points);ymin=min(p[1] for p in points);ymax=max(p[1] for p in points)
def world(f,p):
 a=get(f,'at');t=math.radians(-float(a[2])) if len(a)>2 else 0
 x=float(a[0])+p[0]*math.cos(t)-p[1]*math.sin(t)
 y=float(a[1])+p[0]*math.sin(t)+p[1]*math.cos(t)
 return [round(x-xmin,5),round(ymax-y,5)]
def bounds(f,layer,types):
 pts=[]
 for a in f:
  if not isinstance(a,list) or a[0] not in types or get(a,'layer')!=[layer]:continue
  for k in ['start','end']:pts.append(world(f,list(map(float,get(a,k)[:2]))))
 return [min(p[0] for p in pts),min(p[1] for p in pts),max(p[0] for p in pts),max(p[1] for p in pts)]
fp=kids(b,'footprint'); holes=[];keys=[]
for f in fp:
 ref=prop(f,'Reference')
 if ref.startswith('H'):holes.append((ref,world(f,[0,0])))
 if 'SW_Hotswap_Kailh_MX' in f[1]:keys.append((ref,world(f,[0,0]),bounds(f,'Dwgs.User',['fp_line'])))
 if ref=='U2':
  oled_body=bounds(f,'F.Fab',['fp_rect']);oled_view=bounds(f,'Dwgs.User',['fp_rect'])
  oled_pins=[world(f,list(map(float,get(p,'at')[:2]))) for p in sorted(kids(f,'pad'),key=lambda p:p[1])]
 if ref=='J1':usb=world(f,[0,0])
holes.sort();keys.sort()
data={'pcb_size':[xmax-xmin,ymax-ymin],'pcb_thickness':float(get(kids(b,'general')[0],'thickness')[0]),'mount_holes':[p for _,p in holes],'key_centres':[p for _,p,_ in keys],'keycap_bounds':[q for _,_,q in keys],'oled_body_bounds':oled_body,'oled_view_bounds':oled_view,'oled_pins':oled_pins,'usb_centre':usb,'coordinate_system':'X right, Y towards USB edge, Z up; board bottom-left is [0,0]'}
(GENERATED/'pcb_geometry.json').write_text(json.dumps(data,indent=2)+'\n')
with (GENERATED/'pcb_geometry.scad').open('w') as out:
 out.write('// Generated by tools/extract_pcb.py. XY from the actual board, in mm.\n')
 for k,v in data.items():
  if k!='coordinate_system':out.write(f'pcb_{k} = {json.dumps(v)};\n')
print('Extracted PCB geometry and silkscreen into build/generated/.')

# Actual front silkscreen for the exposed-board renderer, not proposed artwork.
silk=[]
for f in fp:
 for primitive in f:
  if not isinstance(primitive,list) or get(primitive,'layer')!=['F.SilkS']:continue
  typ=primitive[0]
  if typ in ['fp_line','fp_rect','fp_circle','fp_arc','fp_poly']:
   entry={'type':typ,'width':float(get(get(primitive,'stroke'),'width',['0.15'])[0])}
   for key in ['start','mid','end','center']:
    if get(primitive,key):entry[key]=world(f,list(map(float,get(primitive,key)[:2])))
   if typ=='fp_poly':entry['pts']=[world(f,list(map(float,p[1:3]))) for p in get(primitive,'pts')]
   silk.append(entry)
  elif typ in ['property','fp_text']:
   if get(primitive,'hide')==['yes'] or 'hide' in primitive:continue
   text=primitive[2]
   if '${' in text:continue
   font=get(get(primitive,'effects'),'font');at=get(primitive,'at');fa=get(f,'at')
   silk.append({'type':'text','text':text,'at':world(f,list(map(float,at[:2]))),
                'height':float(get(font,'size',['1','1'])[1]),'angle':float(at[2]) if len(at)>2 else (float(fa[2]) if len(fa)>2 else 0)})
(GENERATED/'pcb_silkscreen.json').write_text(json.dumps(silk,indent=2)+'\n')
